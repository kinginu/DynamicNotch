#!/usr/bin/env python3
"""Generate Localization/en.lproj/Localizable.strings for the Xcode app target.

The app is English-only (user decision 2026-10-20): only en.lproj is shipped. Every entry is an
identity mapping (key = English text, as looked up by String(localized:), NSLocalizedString and
SwiftUI's LocalizedStringKey). Source: Support/strings/*.json — one file per feature
(weather.json, timer.json, fan-control.json, …), read in file-name order. Schema (no other fields
allowed):
         {
           "comment": "Weather widget (Open-Meteo)",          # optional, for humans
           "keys":    ["Weather", "Temperature %@", …],         # identity entries
           "entries": {"some.key": "English text"}            # optional, non-identity entries
         }

Rules: a key listed twice in the same source file is an error; the same key in several sources
is merged when the values agree and is an error when they differ (the message names every
source). The output is sorted by key (code-point order), so it does not depend on where a key
is declared.

Usage (from DynamicNotchApp/):
    python3 -I Support/merge-strings.py            # regenerate (writes only when it changed)
    python3 -I Support/merge-strings.py --check    # exit 1 if the generated file is stale
Then lint the Swift sources against the result: python3 -I Support/lint-strings.py
"""
import argparse
import glob
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
APP = os.path.dirname(HERE)
ROOT = os.path.dirname(APP)
DATA_DIR = os.path.join(HERE, "strings")
OUT_PATH = os.path.join(APP, "Localization", "en.lproj", "Localizable.strings")
HEADER = "/* GENERATED by Support/merge-strings.py — do not edit. Source: Support/strings/*.json. */\n\n"

ALLOWED_FIELDS = {"comment", "keys", "entries"}


class StringsError(Exception):
    pass


def rel(path):
    return os.path.relpath(path, ROOT)


def quote(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


# ---------------------------------------------------------------------------------------------
# Sources

def load_json_source(path):
    origin = rel(path)
    try:
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
    except (OSError, ValueError) as e:
        raise StringsError(f"{origin}: {e}")
    if not isinstance(data, dict):
        raise StringsError(f"{origin}: top level must be an object")
    extra = set(data) - ALLOWED_FIELDS
    if extra:
        raise StringsError(f"{origin}: unknown field(s) {sorted(extra)}")
    if "comment" in data and not isinstance(data["comment"], str):
        raise StringsError(f"{origin}: 'comment' must be a string")
    keys = data.get("keys", [])
    entries = data.get("entries", {})
    if not isinstance(keys, list) or not all(isinstance(k, str) for k in keys):
        raise StringsError(f"{origin}: 'keys' must be a list of strings")
    if not isinstance(entries, dict) or not all(isinstance(v, str) for v in entries.values()):
        raise StringsError(f"{origin}: 'entries' must map strings to strings")
    pairs = [(k, k) for k in keys] + list(entries.items())
    return origin, pairs


def sources():
    """[(origin, [(key, value)])] in merge order."""
    if not os.path.isdir(DATA_DIR):
        raise StringsError(f"{rel(DATA_DIR)}/ not found")
    return [load_json_source(p) for p in sorted(glob.glob(os.path.join(DATA_DIR, "*.json")))]


def collect():
    """Return (entries {key: value}, origins {key: [origin, …]}). Raises StringsError on conflicts."""
    entries, origins, problems = {}, {}, []
    for origin, pairs in sources():
        seen = set()
        for k, v in pairs:
            if not k:
                problems.append(f"{origin}: empty key")
                continue
            if any(ord(c) < 0x20 and c != "\n" for c in k + v):
                problems.append(f"{origin}: control character in {k!r}")
            if k in seen:
                problems.append(f"{origin}: duplicate key {k!r}")
                continue
            seen.add(k)
            if k in entries and entries[k] != v:
                problems.append(f"conflict for {k!r}: {entries[k]!r} ({', '.join(origins[k])}) vs {v!r} ({origin})")
                continue
            entries.setdefault(k, v)
            origins.setdefault(k, []).append(origin)
    if problems:
        raise StringsError("\n".join(problems))
    return entries, origins


def render(entries):
    return HEADER + "".join(f"{quote(k)} = {quote(entries[k])};\n" for k in sorted(entries))


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate Localization/en.lproj/Localizable.strings.")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if the output is stale")
    args = ap.parse_args(argv)
    try:
        entries, _ = collect()
    except StringsError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    text = render(entries)
    try:
        with open(OUT_PATH, encoding="utf-8") as f:
            current = f.read()
    except OSError:
        current = None
    if args.check:
        if current != text:
            print(f"{rel(OUT_PATH)} is stale; run python3 -I Support/merge-strings.py", file=sys.stderr)
            return 1
        print(f"{rel(OUT_PATH)}: up to date ({len(entries)} entries)")
        return 0
    if current == text:
        print(f"{rel(OUT_PATH)}: unchanged ({len(entries)} entries)")
    else:
        os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
        with open(OUT_PATH, "w", encoding="utf-8") as f:
            f.write(text)
        print(f"{rel(OUT_PATH)}: {len(entries)} entries")
    if shutil.which("plutil"):
        subprocess.check_call(["plutil", "-lint", "-s", OUT_PATH])
    return 0


if __name__ == "__main__":
    sys.exit(main())
